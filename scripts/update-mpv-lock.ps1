<#
.SYNOPSIS
  Freezes an mpv for the releases and updates scripts/mpv.lock in one step.

.DESCRIPTION
  The everyday mpv (zhongfly, updated by its updater.bat) changes often; the one used for
  releases must only change on purpose (#87). This script:
    1. takes the source mpv.exe (default: the one in PATH);
    2. shows its path, size, date and hash, and the old lock;
    3. after confirmation, copies it to a frozen folder (default:
       %LOCALAPPDATA%\Seaglass-build\mpv.exe), which zhongfly's updater does not touch;
    4. checks the hash of the copy, then reads its version (only the copy is run);
    5. rewrites scripts/mpv.lock and sets the user variable SEAGLASS_MPV_PATH to the copy,
       which release.ps1 reads first.
  Nothing is committed: the git command to run is shown at the end.

.EXAMPLE
  powershell -File scripts/update-mpv-lock.ps1
  powershell -File scripts/update-mpv-lock.ps1 -Source "C:\Program Files\mpv\mpv.exe"
#>
param(
    # mpv.exe to freeze (default: the one in PATH).
    [string]$Source,
    # Location of the frozen copy (default: %LOCALAPPDATA%\Seaglass-build\mpv.exe).
    [string]$Destination = (Join-Path $env:LOCALAPPDATA 'Seaglass-build\mpv.exe'),
    # Do not ask for confirmation (the binary has already been checked).
    [switch]$Yes
)

$ErrorActionPreference = 'Stop'
function Fail($message) { Write-Host "ERROR: $message" -ForegroundColor Red; exit 1 }

$lockPath = Join-Path $PSScriptRoot 'mpv.lock'

# --- Source -----------------------------------------------------------------------------
if (-not $Source) {
    $Source = (Get-Command mpv.exe -ErrorAction SilentlyContinue).Source
    if (-not $Source) { Fail "mpv.exe not found in PATH (specify -Source)" }
}
if (-not (Test-Path -LiteralPath $Source -PathType Leaf)) { Fail "file not found: $Source" }
$Source = (Resolve-Path -LiteralPath $Source).Path
$Destination = [IO.Path]::GetFullPath($Destination)
$file = Get-Item -LiteralPath $Source
$hash = (Get-FileHash -LiteralPath $Source -Algorithm SHA256).Hash

# --- Old lock ----------------------------------------------------------------------
$old = @{}
if (Test-Path $lockPath) {
    Get-Content $lockPath -Encoding UTF8 | Where-Object { $_ -match '^\s*[^#\s]' } | ForEach-Object {
        $name, $value = $_ -split '=', 2
        $old[$name.Trim()] = "$value".Trim()
    }
}

Write-Host "mpv to freeze for the releases"
Write-Host "    file     : $Source"
Write-Host ("    size     : {0:N1} MB, modified {1:yyyy-MM-dd HH:mm}" -f ($file.Length / 1MB), $file.LastWriteTime)
Write-Host "    SHA-256  : $hash"
Write-Host "    lock     : $($old.version), $($old.sha256)"
Write-Host "    copy     : $Destination"
if ($old.sha256 -and $hash -eq $old.sha256.ToUpperInvariant() -and $Source -eq $Destination) {
    Write-Host "Already frozen and matching mpv.lock: nothing to do." -ForegroundColor Green
    exit 0
}

if (-not $Yes) {
    $answer = Read-Host "Freeze this binary and bundle it in the next releases? (y/N)"
    if ($answer -notmatch '^(o|oui|y|yes)$') { Write-Host "Cancelled, nothing changed."; exit 1 }
}

# --- Frozen copy ------------------------------------------------------------------------
# Copied next to it then renamed: an interrupted copy never replaces the previous one.
if ($Source -ne $Destination) {
    New-Item -ItemType Directory -Force (Split-Path $Destination) | Out-Null
    $partial = "$Destination.partial"
    Copy-Item -LiteralPath $Source $partial -Force
    if ((Get-FileHash -LiteralPath $partial -Algorithm SHA256).Hash -ne $hash) {
        Remove-Item -LiteralPath $partial -Force
        Fail "the copy does not match the source (file modified during the copy?)"
    }
    Move-Item -LiteralPath $partial $Destination -Force
}
if ((Get-FileHash -LiteralPath $Destination -Algorithm SHA256).Hash -ne $hash) { Fail "frozen copy altered: $Destination" }

# Version read from the checked copy, never from the source (which may change meanwhile).
$version = ((& $Destination --version | Select-Object -First 1) -split '\s+' | Select-Object -First 2) -join ' '
if ($version -notmatch '^mpv \S+$') { Fail "unreadable version: '$version'" }

# --- mpv.lock ---------------------------------------------------------------------------
$lock = @(
    "# mpv bundled by the installer (#87). ``release.ps1`` refuses any other binary.",
    "# Generated by ``scripts/update-mpv-lock.ps1``, which also freezes the copy read by release.ps1",
    "# (SEAGLASS_MPV_PATH): check the new mpv, run the script, commit this file.",
    "# x86-64-v3 build (AVX2 required, #92) by zhongfly, taken on $(Get-Date -Format 'yyyy-MM-dd').",
    "version=$version",
    "sha256=$hash",
    ""
) -join "`n"
[IO.File]::WriteAllText($lockPath, $lock, (New-Object Text.UTF8Encoding $false))

# --- SEAGLASS_MPV_PATH ------------------------------------------------------------------
if ([Environment]::GetEnvironmentVariable('SEAGLASS_MPV_PATH', 'User') -ne $Destination) {
    [Environment]::SetEnvironmentVariable('SEAGLASS_MPV_PATH', $Destination, 'User')
    Write-Host "SEAGLASS_MPV_PATH (user variable) = $Destination"
    Write-Host "    effective in new terminals; here: `$env:SEAGLASS_MPV_PATH = '$Destination'"
}

Write-Host "mpv.lock updated: $version" -ForegroundColor Green
Write-Host "    to commit: git commit -m `"chore(release): mpv $($version -replace '^mpv ', '')`" scripts/mpv.lock"
