//! Filter on the content offered by the service: explicit (#368) or AI-generated
//! (#369, hidden by default) tracks and albums removed from the lists.
//!
//! The filter applies to what the service offers (search, album / artist pages,
//! other people's playlists, mixes, radios, home, news feed, Jam, automatic radio,
//! local smart playlists #383, computed by the app),
//! never to what the user saved themselves (favorites, their own playlists):
//! they chose them, and changes to a playlist go through the position of the tracks.
//!
//! The setting lives in `UiSettings::content`; its global copy, updated at startup and
//! on every save, avoids rereading SQLite for each list (and is used outside
//! commands: the actor's automatic radio, Jam).

use std::sync::atomic::{AtomicBool, Ordering};

use serde::{Deserialize, Serialize};

use crate::tidal::models::{
    AlbumPage, AlbumRelated, AlbumSummary, ArtistExtra, ArtistPage, ContributorPage, FeedItem,
    HomeRow, MediaItem, MixPage, PlaylistPage, RadioPage, SearchResults, Track,
};

// Values of `ContentFilter::default()` until the first `apply`.
static HIDE_EXPLICIT: AtomicBool = AtomicBool::new(false);
static HIDE_AI: AtomicBool = AtomicBool::new(true);

/// "Content" setting: what is hidden from what the service offers.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct ContentFilter {
    /// Hides the tracks and albums marked explicit (`explicit`). Off by default.
    pub hide_explicit: bool,
    /// Hides the tracks and albums generated by AI according to the service (`ai`, #369). On by
    /// default, settings saved before 0.5.29 included.
    pub hide_ai: bool,
}

impl Default for ContentFilter {
    fn default() -> Self {
        Self {
            hide_explicit: false,
            hide_ai: true,
        }
    }
}

impl ContentFilter {
    /// Filter in force.
    pub fn current() -> Self {
        Self {
            hide_explicit: HIDE_EXPLICIT.load(Ordering::Relaxed),
            hide_ai: HIDE_AI.load(Ordering::Relaxed),
        }
    }

    /// Makes this setting effective for the next lists.
    pub fn apply(self) {
        HIDE_EXPLICIT.store(self.hide_explicit, Ordering::Relaxed);
        HIDE_AI.store(self.hide_ai, Ordering::Relaxed);
    }

    pub fn allows_track(&self, track: &Track) -> bool {
        !(self.hide_explicit && track.explicit || self.hide_ai && track.ai)
    }

    pub fn allows_album(&self, album: &AlbumSummary) -> bool {
        !(self.hide_explicit && album.explicit || self.hide_ai && album.ai)
    }

    fn allows_item(&self, item: &MediaItem) -> bool {
        match item {
            MediaItem::Album(album) => self.allows_album(album),
            MediaItem::Artist(_) | MediaItem::Playlist(_) | MediaItem::Mix(_) => true,
        }
    }

    fn tracks(&self, tracks: &mut Vec<Track>) {
        tracks.retain(|t| self.allows_track(t));
    }

    fn albums(&self, albums: &mut Vec<AlbumSummary>) {
        albums.retain(|a| self.allows_album(a));
    }
}

/// List or page from which what the filter hides is removed.
pub trait Filtered {
    fn filter_with(&mut self, filter: &ContentFilter);
}

/// `value` without what the filter in force hides.
pub fn filtered<T: Filtered>(mut value: T) -> T {
    value.filter_with(&ContentFilter::current());
    value
}

impl Filtered for Vec<Track> {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.tracks(self);
    }
}

impl Filtered for Vec<AlbumSummary> {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.albums(self);
    }
}

impl Filtered for Option<AlbumSummary> {
    fn filter_with(&mut self, filter: &ContentFilter) {
        if self.as_ref().is_some_and(|a| !filter.allows_album(a)) {
            *self = None;
        }
    }
}

impl Filtered for SearchResults {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.tracks(&mut self.tracks);
        filter.albums(&mut self.albums);
    }
}

/// The album itself stays shown (it is reached by a link or a favorite): only its
/// hidden tracks disappear.
impl Filtered for AlbumPage {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.tracks(&mut self.tracks);
    }
}

impl Filtered for AlbumRelated {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.albums(&mut self.versions);
        filter.albums(&mut self.by_artist);
    }
}

impl Filtered for ArtistPage {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.tracks(&mut self.top_tracks);
        filter.albums(&mut self.albums);
        filter.albums(&mut self.singles);
    }
}

impl Filtered for ArtistExtra {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.albums(&mut self.appears_on);
    }
}

/// The user's playlists stay complete (see the module header).
impl Filtered for PlaylistPage {
    fn filter_with(&mut self, filter: &ContentFilter) {
        if !self.playlist.mine {
            self.tracks.retain(|e| filter.allows_track(&e.track));
        }
    }
}

impl Filtered for ContributorPage {
    fn filter_with(&mut self, filter: &ContentFilter) {
        self.tracks.retain(|c| filter.allows_track(&c.track));
    }
}

impl Filtered for MixPage {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.tracks(&mut self.tracks);
    }
}

impl Filtered for RadioPage {
    fn filter_with(&mut self, filter: &ContentFilter) {
        filter.tracks(&mut self.tracks);
    }
}

/// A row emptied by the filter disappears; a row that was already empty stays as it is.
impl Filtered for Vec<HomeRow> {
    fn filter_with(&mut self, filter: &ContentFilter) {
        self.retain_mut(|row| {
            let before = row.items.len();
            row.items.retain(|i| filter.allows_item(i));
            before == 0 || !row.items.is_empty()
        });
    }
}

impl Filtered for Vec<FeedItem> {
    fn filter_with(&mut self, filter: &ContentFilter) {
        self.retain(|f| filter.allows_item(&f.item));
    }
}

impl Filtered for Option<PlaylistPage> {
    fn filter_with(&mut self, filter: &ContentFilter) {
        if let Some(page) = self {
            page.filter_with(filter);
        }
    }
}

